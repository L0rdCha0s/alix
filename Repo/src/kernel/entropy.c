#include "entropy.h"

#include "errno.h"
#include "libc.h"
#include "spinlock.h"
#include "user_copy.h"

#define ENTROPY_WORD_ATTEMPTS 10u

static bool entropy_cpu_has_rdrand(void)
{
    uint32_t eax, ebx, ecx, edx;
    __asm__ volatile ("cpuid" : "=a"(eax), "=b"(ebx), "=c"(ecx), "=d"(edx)
                      : "a"(0u), "c"(0u));
    if (eax < 1u)
    {
        return false;
    }
    __asm__ volatile ("cpuid" : "=a"(eax), "=b"(ebx), "=c"(ecx), "=d"(edx)
                      : "a"(1u), "c"(0u));
    return (ecx & (1u << 30)) != 0;
}

static bool entropy_rdrand_step(uint64_t *word)
{
    uint64_t value;
    unsigned char ready;
    __asm__ volatile ("rdrand %0; setc %1" : "=r"(value), "=qm"(ready) :: "cc");
    if (ready)
    {
        *word = value;
    }
    /* The carry flag alone decides success; zero is a valid random value. */
    return ready != 0;
}

static bool entropy_fill(uint8_t *buffer, size_t length)
{
    size_t filled = 0;
    while (filled < length)
    {
        uint64_t word = 0;
        bool ready = false;
        for (unsigned attempt = 0; attempt < ENTROPY_WORD_ATTEMPTS; ++attempt)
        {
            if (entropy_rdrand_step(&word))
            {
                ready = true;
                break;
            }
            __asm__ volatile ("pause");
        }
        if (!ready)
        {
            return false;
        }
        size_t count = length - filled;
        if (count > sizeof(word))
        {
            count = sizeof(word);
        }
        memcpy(buffer + filled, &word, count);
        filled += count;
    }
    return true;
}

static void entropy_clear(uint8_t *buffer, size_t length)
{
    volatile uint8_t *bytes = buffer;
    while (length--)
    {
        *bytes++ = 0;
    }
}

ssize_t syscall_do_getrandom(void *user_buffer, size_t length, uint32_t flags)
{
    if (flags & ~ENTROPY_NONBLOCK)
    {
        return -EINVAL;
    }
    if (length == 0)
    {
        return 0;
    }
    size_t count = length > ENTROPY_MAX_BYTES ? ENTROPY_MAX_BYTES : length;
    if (!user_ptr_range_valid(user_buffer, count))
    {
        return -EFAULT;
    }

    /* Pin this execution to its CPU while testing that CPU's feature bit.
     * More importantly, process cancellation must not discard a kernel stack
     * that still owns this heap buffer. IRQs remain enabled; there is no sleep
     * or asynchronous handoff, and the work is bounded to 256 bytes/320 tries. */
    spinlock_preempt_disable();
    if (!entropy_cpu_has_rdrand())
    {
        spinlock_preempt_enable();
        return -ENOSYS;
    }
    uint8_t *buffer = malloc(count);
    if (!buffer)
    {
        spinlock_preempt_enable();
        return -ENOMEM;
    }

    ssize_t result;
    if (!entropy_fill(buffer, count))
    {
        /* Never expose uninitialized or partially generated output on failure.
         * No clocks, seeds, counters, or software PRNG substitute for RDRAND. */
        result = (flags & ENTROPY_NONBLOCK) ? -EAGAIN : -EIO;
    }
    else if (!user_copy_to_user(user_buffer, buffer, count))
    {
        /* The shared copy contract permits a copied prefix if a later page is
         * inaccessible. All bytes copied are generated bytes, never heap data. */
        result = -EFAULT;
    }
    else
    {
        result = (ssize_t)count;
    }
    entropy_clear(buffer, count);
    free(buffer);
    spinlock_preempt_enable();
    return result;
}
