#!/usr/bin/env python3
"""Encode pinned TZif bytes and independent Python zoneinfo reference cases."""
from datetime import datetime, timezone
import hashlib
import io
import json
from pathlib import Path
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "fixtures/timezone"
manifest = json.loads((DATA / "manifest.json").read_text())
dates = [
    "1800-01-01T12:00:00", "1969-12-31T23:59:59", "2007-06-21T18:11:00", "2007-12-22T06:09:00",
    "2021-01-01T12:00:00", "2024-03-10T06:59:59", "2024-03-10T07:00:00",
    "2024-04-06T14:59:59", "2024-04-06T15:00:00", "2024-04-06T15:59:59", "2024-04-06T16:00:00",
    "2024-10-05T15:29:59", "2024-10-05T15:30:00", "2024-10-05T15:59:59", "2024-10-05T16:00:00",
    "2024-11-03T05:30:00", "2024-11-03T06:30:00", "2038-01-19T03:14:07",
    "2038-01-19T03:14:08", "2200-01-01T12:00:00", "2200-07-01T12:00:00",
]
lines = ["/* Generated by tests/generate_timezone_fixtures.py from pinned TZif data.",
         " * See fixtures/timezone/manifest.json for byte identity and provenance. */",
         "typedef struct {", "    int64_t epoch;",
         "    int year, month, day, hour, minute, second, weekday, yearday, dst, offset;",
         "    const char *name, *formatted;", "} timezone_sample_t;", ""]
for item in manifest["fixtures"]:
    data = (DATA / item["file"]).read_bytes()
    assert len(data) == item["bytes"] and hashlib.sha256(data).hexdigest() == item["sha256"]
    symbol = "timezone_" + item["symbol"]
    lines.append("static const unsigned char " + symbol + "_bytes[] = {")
    for index in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{x:02x}" for x in data[index:index+16]) + ",")
    lines += ["};", "static const timezone_sample_t " + symbol + "_samples[] = {"]
    zone = ZoneInfo.from_file(io.BytesIO(data), key=item["name"])
    for text in dates:
        instant = datetime.fromisoformat(text).replace(tzinfo=timezone.utc)
        local = instant.astimezone(zone)
        values = [int(instant.timestamp()), local.year, local.month, local.day, local.hour, local.minute, local.second,
                  (local.weekday()+1)%7, local.timetuple().tm_yday-1, int(local.dst().total_seconds()!=0),
                  int(local.utcoffset().total_seconds())]
        # C strftime's %z is HHMM. Python datetime extends it with seconds for
        # old local-mean-time offsets; preserve those seconds in tm_gmtoff while
        # formatting the separately specified C representation here.
        offset = int(local.utcoffset().total_seconds())
        magnitude = abs(offset)
        numeric_zone = ("-" if offset < 0 else "+") + f"{magnitude//3600:02}{magnitude//60%60:02}"
        formatted = local.strftime("%Y-%m-%d %H:%M:%S %G-W%V-%u") + " " + numeric_zone + " " + local.tzname()
        lines.append("    {" + str(values[0]) + "LL, " + ", ".join(str(x) for x in values[1:]) + ", " +
                     json.dumps(local.tzname()) + ", " + json.dumps(formatted) + "},")
    lines += ["};", ""]
(ROOT / "timezone_fixtures.h").write_text("\n".join(lines))
print("Pinned timezone fixtures encoded; 63 independent zoneinfo reference cases")
